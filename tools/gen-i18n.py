#!/usr/bin/env python3
"""Generate ui/i18n-data.js from ui/i18n.tsv (columns: zh-CN‖zh-TW‖en‖fr‖es‖ru‖ar‖ja‖ko)."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
langs = ["zh-CN", "zh-TW", "en", "fr", "es", "ru", "ar", "ja", "ko"]
rows = [l.split("‖") for l in (root / "ui/i18n.tsv").read_text(encoding="utf-8").splitlines() if l.strip()]
for i, r in enumerate(rows):
    assert len(r) == 9, f"line {i+1}: {len(r)} columns"
data = {lang: {r[0]: r[j] for r in rows} for j, lang in enumerate(langs) if j > 0}
out = "// Generated by tools/gen-i18n.py from ui/i18n.tsv. Do not edit by hand.\nconst I18N_DATA = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n"
(root / "ui/i18n-data.js").write_text(out, encoding="utf-8")
print(len(rows), "strings")
